export const useAthenaStore = create<AthenaState>()(
  persist(
    (set, get) => ({
      abilities: [],
      memories: DEFAULT_CHARTER_MEMORIES,

      addAbility: (name, description) => {
        const ability: AthenaAbility = {
          id: `ability-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
          name,
          description,
          autoGenerated: false,
          createdAt: Date.now(),
        }
        set(state => ({ abilities: [...state.abilities, ability] }))
      },

      removeAbility: (id) => {
        set(state => ({ abilities: state.abilities.filter(a => a.id !== id) }))
      },

      updateAbility: (id, name, description) => {
        set(state => ({
          abilities: state.abilities.map(a =>
            a.id === id ? { ...a, name, description } : a
          ),
        }))
      },

      addAutoAbility: (name, description) => {
        // Avoid duplicates by name
        const existing = get().abilities.find(a => a.name === name)
        if (existing) return
        const ability: AthenaAbility = {
          id: `ability-auto-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
          name,
          description,
          autoGenerated: true,
          createdAt: Date.now(),
        }
        set(state => ({ abilities: [...state.abilities, ability] }))
      },

      addMemory: (type, content, category) => {
        const memory: AthenaMemory = {
          id: `memory-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
          type,
          content,
          category,
          createdAt: Date.now(),
          updatedAt: Date.now(),
        }
        set(state => ({ memories: [...state.memories, memory] }))
      },

      removeMemory: (id) => {
        set(state => ({ memories: state.memories.filter(m => m.id !== id) }))
      },

      updateMemory: (id, content) => {
        set(state => ({
          memories: state.memories.map(m =>
            m.id === id ? { ...m, content, updatedAt: Date.now() } : m
          ),
        }))
      },

      addAutoMemory: (content) => {
        // Avoid duplicates by content similarity
        const existing = get().memories.find(m => 
          m.type === 'flow' && m.content === content
        )
        if (existing) return
        const memory: AthenaMemory = {
          id: `memory-flow-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
          type: 'flow',
          content,
          createdAt: Date.now(),
          updatedAt: Date.now(),
        }
        set(state => ({ memories: [...state.memories, memory] }))
      },

      clearFlowMemories: () => {
        set(state => ({
          memories: state.memories.filter(m => m.type === 'charter'),
        }))
      },

      getCharterMemories: () => {
        return get().memories.filter(m => m.type === 'charter')
      },

      getFlowMemories: () => {
        return get().memories.filter(m => m.type === 'flow')
      },

      exportAthena: () => {
        return {
          version: '1.0',
          exportedAt: Date.now(),
          abilities: get().abilities,
          memories: get().memories,
        }
      },

      importAthena: (data) => {
        set({
          abilities: data.abilities || [],
          memories: data.memories || DEFAULT_CHARTER_MEMORIES,
        })
      },
    }),
    {
      name: 'athena-storage',
    }
  )
)
