import { create } from 'zustand'
import { persist } from 'zustand/middleware'
import type { AthenaAbility, AthenaMemory, MemoryType, AthenaExportData } from '@types/index'

interface AthenaState {
  abilities: AthenaAbility[]
  memories: AthenaMemory[]
  
  // Abilities
  addAbility: (name: string, description: string) => void
  removeAbility: (id: string) => void
  updateAbility: (id: string, name: string, description: string) => void
  addAutoAbility: (name: string, description: string) => void
  
  // Memories
  addMemory: (type: MemoryType, content: string, category?: string) => void
  removeMemory: (id: string) => void
  updateMemory: (id: string, content: string) => void
  addAutoMemory: (content: string) => void
  clearFlowMemories: () => void
  
  // Charter memories (user-managed, agent cannot change)
  getCharterMemories: () => AthenaMemory[]
  getFlowMemories: () => AthenaMemory[]
  
  // Export / Import
  exportAthena: () => AthenaExportData
  importAthena: (data: AthenaExportData) => void
}

